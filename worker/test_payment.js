// Failed-payment emails (v48). Run: node worker/test_payment.js
const fs = require('fs'), vm = require('vm');
const src = fs.readFileSync(__dirname + '/situation-room-api.worker.js', 'utf8').replace(/\r\n/g, '\n').replace('export default {', 'globalThis.__worker = {');
vm.runInThisContext(src, { filename: 'worker.js' });
let fails = 0;
const check = (name, ok) => { console.log((ok ? 'PASS ' : 'FAIL ') + name); if (!ok) fails++; };
(async function () {
  const sent = [], updates = [];
  let userStatus = 'active';
  globalThis.verifyRazorpaySignature = async () => true;
  globalThis.getFromAirtable = async () => ({ id: 'rec1', fields: { email: 'u@x.com', subscription_status: userStatus } });
  globalThis.updateAirtable = async (t, id, f) => { updates.push(f); };
  globalThis.sendResendEmail = async (m) => { sent.push(m); };
  const fire = async (ev, noSub, paid) => {
    sent.length = 0; updates.length = 0;
    const payload = noSub ? { payment: { entity: { id: 'pay_1' } } } : { subscription: { entity: { id: 'sub_1', notes: { vantage_user_id: 'user_1' }, paid_count: paid } } };
    const req = { text: async () => JSON.stringify({ event: ev, payload }), headers: { get: () => 'sig' } };
    return (await handleRazorpayWebhook(req, { RAZORPAY_WEBHOOK_SECRET: 'x' })).status;
  };
  userStatus = 'active';
  check('pending: 200', (await fire('subscription.pending')) === 200);
  check('pending: one warning email to the user, no status change', sent.length === 1 && sent[0].to === 'u@x.com' && /did not go through/.test(sent[0].subject) && updates.length === 0);
  check('pending email says access continues', /access continues/.test(sent[0].html));
  userStatus = 'active';
  await fire('subscription.halted');
  check('halted: status set to past_due', updates.length === 1 && updates[0].subscription_status === 'past_due');
  check('halted: user email plus founder alert', sent.length === 2 && sent[0].to === 'u@x.com' && /paused/.test(sent[0].subject) && sent[1].to === 'kumarvivek.srv@gmail.com');
  check('halted email links to the subscribe page', /subscribe\.html/.test(sent[0].html));
  userStatus = 'past_due';
  await fire('subscription.halted');
  check('halted repeat: no duplicate emails', sent.length === 0);
  userStatus = 'active';
  await fire('subscription.paused');
  check('paused: status past_due, no payment-failed email', updates.length === 1 && updates[0].subscription_status === 'past_due' && sent.length === 0);
  userStatus = 'trial';
  await fire('subscription.pending');
  check('pending on a non-active user: no email', sent.length === 0);
  userStatus = 'active';
  const st = await fire('payment.failed', true);
  check('payment.failed without a subscription entity: 200, nothing written or sent', st === 200 && sent.length === 0 && updates.length === 0);
  await fire('subscription.charged', false, 3);
  check('renewal charge (paid_count 3) sends the payment-received email and sets active', sent.length === 1 && /Payment received/.test(sent[0].subject) && updates[0].subscription_status === 'active');
  await fire('subscription.charged', false, 1);
  check('first charge (paid_count 1): status set, no duplicate email', sent.length === 0 && updates[0].subscription_status === 'active');
  await fire('subscription.activated', false, 1);
  check('activated sends exactly one welcome email', sent.length === 1 && /Welcome/.test(sent[0].subject));
  // ── v51: checkout proof (verify_razorpay_payment) ──
  const nodeCrypto = require('crypto');
  const SECRET = 'test_key_secret';
  const goodSig = (pid, sid) => nodeCrypto.createHmac('sha256', SECRET).update(pid + '|' + sid).digest('hex');
  let lookup = { ok: true, body: { id: 'sub_1', status: 'active', current_end: 1790000000, notes: { vantage_user_id: 'user_1' } } };
  globalThis.fetch = async () => ({ ok: lookup.ok, status: lookup.ok ? 200 : 500, json: async () => lookup.body });
  globalThis.ensureUserRow = async () => ({ id: 'rec1', fields: { email: 'u@x.com', subscription_status: 'trial' } });
  const env = { RAZORPAY_KEY_ID: 'rzp_live_x', RAZORPAY_KEY_SECRET: SECRET };
  const verify = async (body, uid) => { updates.length = 0; sent.length = 0; const r = await handleVerifyRazorpayPayment(body, uid || 'user_1', env); return { status: r.status, json: await r.json() }; };
  const okBody = { razorpay_payment_id: 'pay_1', razorpay_subscription_id: 'sub_1', razorpay_signature: goodSig('pay_1', 'sub_1') };
  let r = await verify(okBody);
  check('verify: valid proof activates the account', r.status === 200 && r.json.success && updates.length === 1 && updates[0].subscription_status === 'active' && updates[0].razorpay_subscription_id === 'sub_1' && updates[0].next_billing_date === 1790000000000);
  check('verify: sends no email (the webhook sends the welcome)', sent.length === 0);
  r = await verify({ ...okBody, razorpay_signature: 'deadbeef' });
  check('verify: bad signature rejected, nothing written', r.status === 400 && !r.json.success && updates.length === 0);
  r = await verify({ ...okBody, razorpay_subscription_id: 'sub_2' });
  check('verify: signature for a different subscription rejected', r.status === 400 && updates.length === 0);
  r = await verify(okBody, 'someone_else');
  check('verify: subscription owned by another user rejected', r.status === 403 && updates.length === 0);
  lookup = { ok: true, body: { id: 'sub_1', status: 'created', notes: { vantage_user_id: 'user_1' } } };
  r = await verify(okBody);
  check('verify: unpaid subscription (status created) not activated', r.status === 409 && updates.length === 0);
  lookup = { ok: false, body: {} };
  r = await verify(okBody);
  check('verify: Razorpay lookup failure does not activate', r.status === 502 && updates.length === 0);
  lookup = { ok: true, body: { id: 'sub_1', status: 'authenticated', notes: { vantage_user_id: 'user_1' } } };
  r = await verify(okBody);
  check('verify: authenticated status counts as paid', r.status === 200 && updates.length === 1 && !('next_billing_date' in updates[0]));
  r = await verify({ razorpay_payment_id: 'pay_1' });
  check('verify: missing fields rejected', r.status === 400 && updates.length === 0);
  r = await verify({ ...okBody, razorpay_signature: goodSig('pay_1', 'sub_1').toUpperCase() });
  check('verify: upper-case hex signature accepted', r.status === 200);
  check('error response no longer carries _debug', !/_debug/.test(require('fs').readFileSync(__dirname + '/situation-room-api.worker.js', 'utf8')));
  console.log(fails ? 'FAILURES: ' + fails : 'PAYMENT TESTS PASSED');
  process.exit(fails ? 1 : 0);
})();
